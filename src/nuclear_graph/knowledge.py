"""The knowledge base of the whole project as a folder (the `nuclear-knowledge` repository, `nuclear-developer/data`):
every document, example and the help of the command line tools, copied byte for byte from the working tree and the
website and ordered step by step by its `sections.toml`. A file no section claims goes to `99-other`, so none is left
out; `check` fails when the copy and the sources differ in a single byte. The Smart Graph ingests this folder."""

from __future__ import annotations

import hashlib
import json
import shutil
import subprocess
import tomllib
from dataclasses import dataclass
from pathlib import Path, PurePosixPath

from .ingest import SKIP_DIRS

KINDS = (".md", ".nuc", ".ebnf")
NAMED = ("docs.toml", "platform.toml")
PRIVATE = ("docs/aprende", "CodeBuilder")  # the user's teaching material: never published nor ingested
OTHER = {"id": "99-other", "title": "Files no section claims yet: give them a section in sections.toml", "agents": False}
MANIFEST = "manifest.json"
INDEX = "INDEX.md"

# what the command line tools print: generated, kept as files of the section `cli/`
HELP = [
    ("nuclear.txt", ["nuclear", "help"]),
    ("nuclear-dialect-list.txt", ["nuclear", "dialect", "list"]),
    ("dragonfly.txt", ["dragonfly", "--help"]),
    ("nuclear-loop.txt", ["nuclear-loop", "help"]),
    ("nuclear-graph.txt", ["nuclear-graph", "--help"]),
] + [(f"nuclear-help-{w}-{p}.txt", ["nuclear", "help", w, "--platform", p])
     for p in ("backend", "mobile", "web") for w in ("words", "layout")]


@dataclass
class Source:
    rel: str          # the path as the sections name it: `spec/nuclear-base.md`, `website/README.md`, `cli/nuclear.txt`
    data: bytes
    repo: str         # the repository it belongs to: a folder of the tree with its own git, `website`, `cli`, else the tree


def collect(tree: Path, website: Path | None) -> list[Source]:
    """Every knowledge file of the tree and the website, and the help of the tools, sorted by path."""
    out: list[Source] = []
    for root, prefix in [(tree, ""), *([(website, "website/")] if website and website.is_dir() else [])]:
        for path in sorted(root.rglob("*")):
            rel = path.relative_to(root).as_posix()
            parts = rel.split("/")
            if any(p in SKIP_DIRS or (p.startswith(".") and p != ".github") for p in parts[:-1]):
                continue
            if any(rel.startswith(p) for p in PRIVATE) or not path.is_file():
                continue
            if path.suffix in KINDS or path.name in NAMED:
                repo = "website" if prefix else parts[0] if len(parts) > 1 and (root / parts[0] / ".git").exists() else root.name
                out.append(Source(prefix + rel, path.read_bytes(), repo))
    for name, cmd in HELP:
        if shutil.which(cmd[0]):
            r = subprocess.run(cmd, capture_output=True, text=True, timeout=60)
            out.append(Source(f"cli/{name}", f"$ {' '.join(cmd)}\n\n{r.stdout}{r.stderr}".encode(), "cli"))
    return sorted(out, key=lambda s: s.rel)


def matches(rel: str, globs: list[str]) -> bool:
    p = PurePosixPath(rel)
    return any(p.full_match(g) for g in globs)


def plan(sections_file: Path, sources: list[Source]) -> tuple[list[dict], list[dict]]:
    """The sections in order and every file with its section: the first section whose globs match it."""
    spec = tomllib.loads(sections_file.read_text())
    sections = [{"id": s["id"], "title": s["title"], "agents": s.get("agents", True), "files": s["files"]} for s in spec["section"]]
    files = []
    for src in sources:
        if matches(src.rel, spec.get("exclude", [])):
            continue
        section = next((s for s in sections if matches(src.rel, s["files"])), OTHER)
        files.append({"path": f"{section['id']}/{src.rel}", "source": src.rel, "repo": src.repo, "section": section["id"],
                      "agents": section["agents"], "bytes": len(src.data), "sha256": hashlib.sha256(src.data).hexdigest(),
                      "_data": src.data})
    used = {f["section"] for f in files}
    ordered = [s for s in sections if s["id"] in used] + ([OTHER] if OTHER["id"] in used else [])
    return [{k: v for k, v in s.items() if k != "files"} for s in ordered], files


def index_md(sections: list[dict], files: list[dict]) -> str:
    lines = ["# The knowledge base of NuclearLang", "",
             "Generated by `nuclear-graph knowledge build` from the working tree (never edit a copy: change its source,",
             "then build again). Read it in this order. *(people)*: the local agents do not read that section.", ""]
    for s in sections:
        mine = [f for f in files if f["section"] == s["id"]]
        lines += [f"## {s['id']} — {s['title']}{'' if s['agents'] else ' *(people)*'}", ""]
        lines += [f"- [`{f['source']}`]({f['path']})" for f in mine] + [""]
    return "\n".join(lines)


def generated(out: Path) -> list[Path]:
    """What a build wrote before (the section folders, the index and the manifest), never the repository's own files."""
    return [p for p in out.iterdir() if (p.is_dir() and p.name[:2].isdigit() and p.name[2:3] == "-") or p.name in (INDEX, MANIFEST)]


def website_of(out: Path) -> Path | None:
    """The website's checkout (`website` in sections.toml, `~` allowed), when it is there."""
    w = tomllib.loads((out / "sections.toml").read_text()).get("website")
    return Path(w).expanduser() if w and Path(w).expanduser().is_dir() else None


def build(tree: Path, out: Path, website: Path | None) -> dict:
    sections, files = plan(out / "sections.toml", collect(tree, website))
    for p in generated(out):
        shutil.rmtree(p) if p.is_dir() else p.unlink()
    for f in files:
        target = out / f["path"]
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(f["_data"])
    clean = [{k: v for k, v in f.items() if k != "_data"} for f in files]
    (out / MANIFEST).write_text(json.dumps({"sections": sections, "files": clean}, indent=1) + "\n")
    (out / INDEX).write_text(index_md(sections, clean))
    return {"files": len(files), "sections": len(sections), "unclaimed": [f["source"] for f in files if f["section"] == OTHER["id"]]}


def check(tree: Path, out: Path, website: Path | None) -> list[str]:
    """Every difference between the sources and the copy: a missing, extra or changed file, or a stale manifest."""
    _, files = plan(out / "sections.toml", collect(tree, website))
    problems = []
    want = {f["path"]: f for f in files}
    have = {p.relative_to(out).as_posix() for d in generated(out) if d.is_dir() for p in d.rglob("*") if p.is_file()}
    for path, f in want.items():
        target = out / path
        if not target.is_file():
            problems.append(f"missing: {path} (from {f['source']})")
        elif target.read_bytes() != f["_data"]:
            problems.append(f"changed: {path} differs from {f['source']}")
    problems += [f"extra: {p} (its source is gone or moved)" for p in sorted(have - set(want))]
    try:
        manifest = json.loads((out / MANIFEST).read_text())
        listed = {f["path"]: f["sha256"] for f in manifest["files"]}
        if listed != {p: f["sha256"] for p, f in want.items()}:
            problems.append(f"{MANIFEST} is not the one of these sources: build again")
    except (OSError, ValueError, KeyError):
        problems.append(f"{MANIFEST} is missing or unreadable: build again")
    return problems
